export type InlineCitationCarouselIndexProps = ComponentProps<"div">;

export const InlineCitationCarouselIndex = ({
  children,
  className,
  ...props
}: InlineCitationCarouselIndexProps) => {
  const api = useCarouselApi();
  const [current, setCurrent] = useState(0);
  const [count, setCount] = useState(0);

  const syncState = useCallback(() => {
    if (!api) {
      return;
    }
    setCount(api.scrollSnapList().length);
    setCurrent(api.selectedScrollSnap() + 1);
  }, [api]);

  useEffect(() => {
    if (!api) {
      return;
    }

    // Vendored change: deferred to a microtask so setState is not called synchronously in the effect body (react-hooks/set-state-in-effect).
    queueMicrotask(syncState);

    api.on("select", syncState);

    return () => {
      api.off("select", syncState);
    };
  }, [api, syncState]);

  return (
    <div
      className={cn(
        "flex flex-1 items-center justify-end px-3 py-1 type-small text-muted-foreground",
        className
      )}
      {...props}
    >
      {children ?? `${current}/${count}`}
    </div>
  );
};

export type InlineCitationCarouselPrevProps = ComponentProps<"button">;

export const InlineCitationCarouselPrev = ({
  className,
  ...props
}: InlineCitationCarouselPrevProps) => {
  const api = useCarouselApi();

  const handleClick = useCallback(() => {
    if (api) {
      api.scrollPrev();
    }
  }, [api]);

  // Vendored change: the raw `<button>` had no hit target at all beyond its 16px icon — replaced with `Button` so it has a real interactive target.
  return (
    <Button
      aria-label="Previous"
      className={cn("shrink-0", className)}
      onClick={handleClick}
      size="icon-sm"
      type="button"
      variant="ghost"
      {...props}
    >
      <Icon icon={ArrowLeftIcon} tone="muted" />
    </Button>
  );
};

