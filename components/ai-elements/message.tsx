export type MessageResponseProps = ComponentProps<typeof Streamdown>;

const streamdownPlugins = { cjk, code, math, mermaid };

/* Vendored change: the reply speaks the system's type, colour and code roles. */
const PLAIN_TAGS = [
  "h1",
  "h2",
  "h3",
  "h4",
  "h5",
  "h6",
  "p",
  "ul",
  "ol",
  "li",
  "blockquote",
  "hr",
  "strong",
  "em",
  "th",
  "td",
] as const;

type PlainTag = (typeof PLAIN_TAGS)[number] | "code";

const plain = (tag: PlainTag) => {
  const Plain = (all: HTMLAttributes<HTMLElement> & ExtraProps) => {
    const props: Record<string, unknown> = { ...all };
    delete props.node;
    delete props.className;
    return createElement(tag, props);
  };
  Plain.displayName = `Plain(${tag})`;
  return Plain;
};

const plainComponents: Record<string, ReturnType<typeof plain>> = { inlineCode: plain("code") };
for (const tag of PLAIN_TAGS) plainComponents[tag] = plain(tag);
const streamdownComponents = plainComponents as Components;

const LinkCheck = ({ isOpen, onClose, onConfirm, url }: LinkSafetyModalProps) => (
  <AlertDialog onOpenChange={(open) => (open ? undefined : onClose())} open={isOpen}>
    <AlertDialogContent>
      <AlertDialogHeader>
        <AlertDialogTitle>Open this link?</AlertDialogTitle>
        <AlertDialogDescription className="break-all">{url}</AlertDialogDescription>
      </AlertDialogHeader>
      <AlertDialogFooter>
        <AlertDialogCancel>Cancel</AlertDialogCancel>
        <AlertDialogAction onClick={onConfirm} variant="default">
          Open link
        </AlertDialogAction>
      </AlertDialogFooter>
    </AlertDialogContent>
  </AlertDialog>
);

const streamdownLinkSafety = {
  enabled: true,
  renderModal: (props: LinkSafetyModalProps) => <LinkCheck {...props} />,
};

const DiagramError = ({ error, retry }: MermaidErrorComponentProps) => (
  <Alert variant="destructive">
    <Icon icon={TriangleAlertIcon} tone="inherit" />
    <AlertTitle>This diagram could not be drawn</AlertTitle>
    <AlertDescription>
      <p className="type-code break-all">{error}</p>
      <Button className="mt-2 w-fit" onClick={retry} size="sm" type="button" variant="outline">
        Try again
      </Button>
    </AlertDescription>
  </Alert>
);

const streamdownMermaid = { errorComponent: DiagramError };
const streamdownShikiTheme: ComponentProps<typeof Streamdown>["shikiTheme"] = [
  SYSTEM_CODE_THEME,
  SYSTEM_CODE_THEME,
];

export const MessageResponse = memo(
  ({ className, ...props }: MessageResponseProps) => (
    <Streamdown
      className={cn(
        "prose streamdown-chrome size-full [&>*:first-child]:mt-0 [&>*:last-child]:mb-0",
        className
      )}
      components={streamdownComponents}
      linkSafety={streamdownLinkSafety}
      mermaid={streamdownMermaid}
      plugins={streamdownPlugins}
      shikiTheme={streamdownShikiTheme}
      {...props}
    />
  ),
  (prevProps, nextProps) =>
    prevProps.children === nextProps.children &&
    nextProps.isAnimating === prevProps.isAnimating
);

MessageResponse.displayName = "MessageResponse";

