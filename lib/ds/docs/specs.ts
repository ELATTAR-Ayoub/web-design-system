export function hasSpec(name: string): boolean {
  return Object.hasOwn(LOADERS, name);
}

export async function loadSpec(name: string): Promise<ComponentDocSpec | null> {
  const load = LOADERS[name];
  if (!load) return null;
  return (await load()).spec;
}

/** Every documented name, for `generateStaticParams`. */
export function specNames(): string[] {
  return Object.keys(LOADERS);
}
