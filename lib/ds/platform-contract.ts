const byName = new Map(PLATFORM_CONTRACT.map((e) => [e.name, e]));

export function contractEntry(name: string): ContractEntry | undefined {
  return byName.get(name);
}

export function contractEntriesIn(family: DocFamily): readonly ContractEntry[] {
  return PLATFORM_CONTRACT.filter((e) => e.family === family);
}

export function isAdvertised(entry: ContractEntry): boolean {
  return (
    (entry.ownership === "installable" ||
      entry.ownership === "block" ||
      entry.ownership === "foundation") &&
    (entry.delivery === "react" || entry.delivery === "css-native")
  );
}
